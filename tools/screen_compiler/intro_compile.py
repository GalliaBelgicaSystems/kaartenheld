#!/usr/bin/env python3
"""
intro_compile.py - Intro slides JSON to C for the Game Boy RPG.

screens/intro.json -> src/screens/intro_text_generated.h (slide text
arrays + pointer table + per-slide line counts) + src/screens/
intro_count_generated.h (INTRO_SLIDE_COUNT).  The banked render body
stays hand-written in src/screens/title_content.c, which includes the
generated text header: generated initializers must keep the exact
static-const-array shape SDCC compiles correctly (see the s_card_desc
precedent — flat multi-literal initializers miscompile).

Slide geometry: at most 8 rows per slide, each centered by the
compiler in an 18-wide field (cols 1..18, col 0/19 whitespace) and
drawn by the banked renderer vertically centered in rows 2..14 (the
A NEXT footer stays at row 16).  Short slides pad with "".

Usage:
    python3 tools/screen_compiler/intro_compile.py --all -o src/screens/
    python3 tools/screen_compiler/intro_compile.py --all --check
"""
import argparse
import json
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent

INTRO_JSON = "intro.json"
MAX_ROWS = 8
STAGE_COLS = 20     # s_intro_N[][20] incl NUL
RENDER_WIDTH = 18   # draw width (clipped at render)


def load_intro():
    path = REPO_ROOT / "screens" / INTRO_JSON
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"ERROR: cannot read {path}: {exc}", file=sys.stderr)
        sys.exit(1)
    slides = data.get("slides")
    if not isinstance(slides, list) or not slides:
        print(f"ERROR: {path}: need at least 1 slide (the NEW GAME "
              f"intro starts here unconditionally)", file=sys.stderr)
        sys.exit(1)
    errors, warnings = [], []
    rows = []
    for i, slide in enumerate(slides):
        lines = (slide or {}).get("lines", [])
        if not isinstance(lines, list) or not (1 <= len(lines) <= MAX_ROWS):
            errors.append(
                f"slide {i}: need 1..{MAX_ROWS} lines, have "
                f"{len(lines) if isinstance(lines, list) else '?'}")
            continue
        exp = []
        for j, line in enumerate(lines):
            if not isinstance(line, str):
                errors.append(f"slide {i} line {j} must be a string")
                continue
            try:
                raw = line.encode("ascii")
            except UnicodeEncodeError:
                errors.append(
                    f"slide {i} line {j} has non-ASCII chars "
                    f"(the GB font is 96-tile ASCII, no accents)")
                continue
            if len(raw) >= STAGE_COLS:
                errors.append(
                    f"slide {i} line {j} is {len(raw)} chars, exceeds "
                    f"staging ({STAGE_COLS - 1})")
            elif len(raw) > RENDER_WIDTH:
                warnings.append(
                    f"slide {i} line {j} is {len(raw)} chars, wider than "
                    f"the {RENDER_WIDTH}-col box (clipped at render)")
            exp.append(line)
        exp += [""] * (MAX_ROWS - len(exp))
        rows.append(exp)
    for w in warnings:
        print(f"WARNING: {w}")
    if errors:
        for e in errors:
            print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    return rows


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def center_pad(line):
    """Center `line` in the 18-wide text field (cols 1..18): pad both
    sides with spaces so col 0 and col 19 stay blank.  Lines over 18
    chars are rejected by load_intro, so this only ever pads."""
    pad = RENDER_WIDTH - len(line)
    left = pad // 2
    return " " * left + line + " " * (pad - left)


def build_text_output(rows):
    """Generate src/screens/intro_text_generated.h: slide arrays +
    pointer table.  Included ONCE (by title_content.c): static data
    must not duplicate per translation unit.  The slide count and
    per-slide line counts travel separately (see build_count_output)."""
    lines = []
    lines.append("/* Generated by tools/screen_compiler/intro_compile.py --all.")
    lines.append(" * Do not edit directly -- edit screens/intro.json and re-run. */")
    lines.append("#ifndef INTRO_TEXT_GENERATED_H")
    lines.append("#define INTRO_TEXT_GENERATED_H")
    lines.append("")
    for i, slide in enumerate(rows):
        lines.append(f"static const char s_intro_{i}[{MAX_ROWS}][{STAGE_COLS}] = {{")
        for j, line in enumerate(slide):
            comma = "," if j < len(slide) - 1 else ""
            lines.append(f'    "{c_escape(center_pad(line))}"{comma}')
        lines.append("};")
        lines.append("")
    lines.append(f"static const char (* const s_intro_slides[{len(rows)}])[{STAGE_COLS}] = {{")
    for i in range(len(rows)):
        comma = "," if i < len(rows) - 1 else ""
        lines.append(f"    s_intro_{i}{comma}")
    lines.append("};")
    lines.append("")
    lines.append("/* Real line count per slide (the renderer vertically centers")
    lines.append(" * each slide, so it must know where the \"\" padding starts).")
    lines.append(" * Lives here (not in the count header): this header is")
    lines.append(" * included once, by title_content.c. */")
    counts = []
    for slide in rows:
        n = 0
        for line in slide:
            if line == "":
                break
            n += 1
        counts.append(str(n))
    lines.append(f"static const uint8_t s_intro_counts[{len(rows)}] = {{{', '.join(counts)}}};")
    lines.append("")
    lines.append("#endif /* INTRO_TEXT_GENERATED_H */")
    lines.append("")
    return "\n".join(lines)


def build_count_output(rows):
    """Generate src/screens/intro_count_generated.h: just the slide
    count define (included by screen.h — defines duplicate harmlessly,
    unlike the arrays above)."""
    lines = []
    lines.append("/* Generated by tools/screen_compiler/intro_compile.py --all.")
    lines.append(" * Do not edit directly -- edit screens/intro.json and re-run. */")
    lines.append("#ifndef INTRO_COUNT_GENERATED_H")
    lines.append("#define INTRO_COUNT_GENERATED_H")
    lines.append("")
    lines.append(f"#define INTRO_SLIDE_COUNT {len(rows)}")
    lines.append("")
    lines.append("#endif /* INTRO_COUNT_GENERATED_H */")
    lines.append("")
    return "\n".join(lines)


def main(args=None):
    parser = argparse.ArgumentParser(description="Compile intro JSON to C.")
    parser.add_argument("--all", action="store_true",
                        help="Compile screens/intro.json")
    parser.add_argument("-o", "--output", default="src/screens/",
                        help="Output directory for intro_text_generated.h")
    parser.add_argument("--check", action="store_true",
                        help="Do not write; exit nonzero if fresh output "
                             "differs from the file")
    args = parser.parse_args(args)

    outdir = Path(args.output)
    if str(outdir).endswith(".h"):
        outdir = outdir.parent
    rows = load_intro()
    fresh = {
        outdir / "intro_text_generated.h": build_text_output(rows),
        outdir / "intro_count_generated.h": build_count_output(rows),
    }
    if args.check:
        for path, text in fresh.items():
            try:
                committed = path.read_text(encoding="utf-8")
            except FileNotFoundError:
                committed = None
            if committed is None or committed.strip() != text.strip():
                print(f"DRIFT: fresh compile differs from {path}", file=sys.stderr)
                sys.exit(1)
        print(f"intro --check OK: {len(rows)} slide(s) match fresh output")
        return
    for path, text in fresh.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path}")
    print(f"Compiled {len(rows)} intro slide(s)")


if __name__ == "__main__":
    main()
