def validate_title_json(path: Path) -> dict:
    """Validate and return the title JSON data, raising on structural errors."""
    with open(path) as f:
        data = json.load(f)

    # Basic sanity: logo lines must be <= grid_width chars, prompt text <= 20,
    # menu options <= 20 chars, and there must be at least one option.
    grid_w = data.get("grid_width", 20)
    grid_h = data.get("grid_height", 18)

    for i, line in enumerate(data["logo"]["lines"]):
        if len(line) > grid_w:
            print(
                "WARNING: logo line %d has length %d > grid_width %d; will be truncated"
                % (i, len(line), grid_w)
            )

    if len(data["prompt"]["text"]) > 20:
        print(
            "WARNING: prompt text length %d > 20; will be truncated"
            % len(data["prompt"]["text"])
        )

    for opt in data["menu"]["options"]:
        if len(opt) > 20:
            print(
                "WARNING: menu option '%s' has length %d > 20; will be truncated"
                % (opt, len(opt))
            )

    if not data["menu"]["options"]:
        print("WARNING: no menu options defined")

    return data


