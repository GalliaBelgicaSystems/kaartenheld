def build_title_c_output(data: dict) -> str:
    """Build the full C output string from validated title JSON."""
    grid_w = data.get("grid_width", 20)
    grid_h = data.get("grid_height", 18)
    n_logo = len(data["logo"]["lines"])

    logo_rows = data["logo"]["lines"]
    # Pad/truncate each row to exactly grid_w chars
    logo_padded = []
    for line in logo_rows:
        if len(line) >= grid_w:
            logo_padded.append(line[:grid_w])
        else:
            logo_padded.append(line + " " * (grid_w - len(line)))

    # Build logo initializer parts
    logo_init_parts = []
    for row in logo_padded:
        escaped = row.replace('\\', '\\\\').replace('"', '\\"')
        logo_init_parts.append('"%s"' % escaped)
    logo_init = ",\n".join(logo_init_parts)

    # Prompt text padded to 20 chars
    prompt_text = data["prompt"]["text"]
    prompt_align = data["prompt"].get("align")
    if prompt_align == "center":
        prompt_x = max(0, (20 - len(prompt_text.strip())) // 2)
    elif prompt_align == "right":
        prompt_x = max(0, 20 - len(prompt_text.strip()))
    elif prompt_align == "left":
        prompt_x = 0
    else:
        prompt_x = data["prompt"].get("x", 5)
    prompt_y = data["prompt"].get("y", 16)

    prompt_padded = prompt_text + " " * (20 - len(prompt_text))
    escaped_prompt = prompt_padded.replace('\\', '\\\\').replace('"', '\\"')

    # Graphic / Multi-tile Image data
    graphic_data = data.get("graphic", {})
    graphic_enabled = 1 if graphic_data.get("enabled", False) else 0
    graphic_x = graphic_data.get("x", 0)
    graphic_y = graphic_data.get("y", 7)
    graphic_rows = graphic_data.get("lines", [])
    if not graphic_rows:
        graphic_rows = [""]
    n_graphic = len(graphic_rows)
    graphic_padded = []
    for line in graphic_rows:
        if len(line) >= grid_w:
            graphic_padded.append(line[:grid_w])
        else:
            graphic_padded.append(line + " " * (grid_w - len(line)))
    graphic_init_parts = []
    for row in graphic_padded:
        escaped = row.replace('\\', '\\\\').replace('"', '\\"')
        graphic_init_parts.append('"%s"' % escaped)
    graphic_init = ",\n".join(graphic_init_parts)

    # Logo image (bitmap): the tile bytes come from make gfx
    # (src/gfx/title_logo_tiles.inc); this compiles only placement/flags.
    logo_image = data.get("logo_image", {})
    logo_image_enabled = 1 if logo_image.get("enabled", False) else 0
    logo_image_x = logo_image.get("x", 2)
    logo_image_y = logo_image.get("y", 1)
    logo_image_width = logo_image.get("width", 16)
    logo_image_height = logo_image.get("height", 3)
    logo_image_palette = logo_image.get("palette", 1)

    # Subtitle line drawn under the logo.
    subtitle = data.get("subtitle", {})
    subtitle_text = subtitle.get("text", "")
    subtitle_align = subtitle.get("align", "center")
    if subtitle_align == "right":
        subtitle_x = max(0, 20 - len(subtitle_text.strip()))
    elif subtitle_align == "left":
        subtitle_x = subtitle.get("x", 0)
    else:  # center
        subtitle_x = max(0, (20 - len(subtitle_text.strip())) // 2)
    subtitle_y = subtitle.get("y", 5)
    subtitle_padded = subtitle_text + " " * (20 - len(subtitle_text))
    escaped_subtitle = subtitle_padded.replace('\\', '\\\\').replace('"', '\\"')

    # Credits data
    credits_data = data.get("credits", {})
    credits_enabled = 1 if credits_data.get("enabled", False) else 0
    credits_text = credits_data.get("text", "")
    credits_align = credits_data.get("align", "right")
    if credits_align == "right":
        credits_x = max(0, 20 - len(credits_text.strip()))
    elif credits_align == "center":
        credits_x = max(0, (20 - len(credits_text.strip())) // 2)
    elif credits_align == "left":
        credits_x = 0
    else:
        credits_x = credits_data.get("x", 0)
    credits_y = credits_data.get("y", 17)
    credits_padded = credits_text + " " * (20 - len(credits_text))
    escaped_credits = credits_padded.replace('\\', '\\\\').replace('"', '\\"')

    # Menu labels padded to grid_w
    menu_options = data["menu"]["options"]
    menu_label_parts = []
    for opt in menu_options:
        if len(opt) >= grid_w:
            padded = opt[:grid_w]
        else:
            padded = opt + " " * (grid_w - len(opt))
        escaped = padded.replace('\\', '\\\\').replace('"', '\\"')
        menu_label_parts.append('"%s"' % escaped)

    # Build the complete output string
    lines = []
    lines.append("/**")
    lines.append(" * Generated by tools/screen_compiler/title_compile.py.")
    lines.append(" * Do not edit directly — edit screens/title.json and re-run.")
    lines.append(" */")
    lines.append("")
    lines.append("#pragma bank 4")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    # --- Logo ---
    lines.append("const char g_title_logo[%d][%d+1] = {" % (n_logo, grid_w))
    lines.append(logo_init)
    lines.append("};")
    lines.append("")
    # Logo position
    lines.append("uint8_t const g_title_logo_x = %d;" % data["logo"]["x"])
    lines.append("uint8_t const g_title_logo_y = %d;" % data["logo"]["y"])
    lines.append("uint8_t const g_title_logo_count = %d;" % n_logo)
    lines.append("")
    # --- Logo bitmap (placement only; tile bytes in gfx/title_logo_tiles.inc) ---
    lines.append("uint8_t const g_title_logo_image_enabled = %d;" % logo_image_enabled)
    lines.append("uint8_t const g_title_logo_image_x = %d;" % logo_image_x)
    lines.append("uint8_t const g_title_logo_image_y = %d;" % logo_image_y)
    lines.append("uint8_t const g_title_logo_image_width = %d;" % logo_image_width)
    lines.append("uint8_t const g_title_logo_image_height = %d;" % logo_image_height)
    lines.append("uint8_t const g_title_logo_image_palette = %d;" % logo_image_palette)
    lines.append("")
    # --- Subtitle ---
    lines.append("const char g_title_subtitle_text[21] = \"%s\";" % escaped_subtitle)
    lines.append("uint8_t const g_title_subtitle_x = %d;" % subtitle_x)
    lines.append("uint8_t const g_title_subtitle_y = %d;" % subtitle_y)
    lines.append("")
    # --- Graphic / Multi-tile Image ---
    lines.append("const char g_title_graphic[%d][%d+1] = {" % (n_graphic, grid_w))
    lines.append(graphic_init)
    lines.append("};")
    lines.append("")
    lines.append("uint8_t const g_title_graphic_x = %d;" % graphic_x)
    lines.append("uint8_t const g_title_graphic_y = %d;" % graphic_y)
    lines.append("uint8_t const g_title_graphic_count = %d;" % n_graphic)
    lines.append("uint8_t const g_title_graphic_enabled = %d;" % graphic_enabled)
    lines.append("")
    # --- Prompt ---
    lines.append("const char g_title_prompt_text[21] = \"%s\";" % escaped_prompt)
    lines.append("uint8_t const g_title_prompt_x = %d;" % prompt_x)
    lines.append("uint8_t const g_title_prompt_y = %d;" % prompt_y)
    lines.append("")
    # --- Credits ---
    lines.append("const char g_title_credits_text[21] = \"%s\";" % escaped_credits)
    lines.append("uint8_t const g_title_credits_x = %d;" % credits_x)
    lines.append("uint8_t const g_title_credits_y = %d;" % credits_y)
    lines.append("uint8_t const g_title_credits_enabled = %d;" % credits_enabled)
    lines.append("")
    # --- Menu ---
    lines.append("const char g_title_menu_options[%d][%d+1] = {" % (menu_count := len(menu_options), grid_w))
    lines.append(",\n".join(menu_label_parts))
    lines.append("};")
    lines.append("")
    # Menu position
    lines.append("uint8_t const g_title_menu_x = %d;" % data["menu"]["x"])
    lines.append("uint8_t const g_title_menu_caret_x = %d;" % data["menu"]["caret_x"])
    lines.append("uint8_t const g_title_menu_first_row = %d;" % data["menu"]["first_row"])
    lines.append("uint8_t const g_title_menu_row_step = %d;" % data["menu"]["row_step"])
    lines.append("uint8_t const g_title_menu_count = %d;" % menu_count)

    return "\n".join(lines)


def main(args=None):
    parser = argparse.ArgumentParser(description="Title screen content compiler")
    parser.add_argument("input", nargs="?", default=None,
                        help="Path to title JSON (default: screens/title.json)")
    parser.add_argument("-o", "--output", default=None,
                        help="Output C file (default: src/game/title_data.c)")
    parser.add_argument("--validate", action="store_true",
                        help="Only validate JSON, don't emit C")
    parser.add_argument("--check", action="store_true",
                        help="Do not write; exit nonzero if fresh output differs from the file")

    args = parser.parse_args(args)

    input_path = Path(args.input) if args.input else REPO_ROOT / "screens" / "title.json"
    output_path = Path(args.output) if args.output else REPO_ROOT / "src" / "game" / "title_data.c"

    # Validate
    data = validate_title_json(input_path)

    if args.validate:
        print("JSON validation passed: %s" % input_path)
        return 0

    # Emit C
    output_text = build_title_c_output(data)

    if args.check:
        try:
            committed = output_path.read_text(encoding="utf-8")
        except FileNotFoundError:
            committed = None
        if committed is None or committed != output_text:
            print("DRIFT: fresh compile differs from %s" % output_path, file=sys.stderr)
            return 1
        print("title compile --check OK: %s matches fresh output" % output_path)
        return 0

    # Ensure output directory exists
    out_dir = Path(output_path).parent
    out_dir.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        f.write(output_text)

    print("Wrote %s" % output_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())