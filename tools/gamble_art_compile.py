#!/usr/bin/env python3
"""gamble_art_compile.py -- Chuck-a-luck bank-8 art bundle.

Reads the live battle sources and emits src/gfx/gamble_art.h for the
bank-8 gamble entry body (same bank: plain reads, no trampoline, no
cross-bank windowelan):

  g_gamble_kobold_tiles[96]  kobold combat-art frame0 bytes (3x2 tiles)
  g_gamble_kobold_ramp[8]    fightgoblin OBJ ramp bytes (CGB order, low first)
  g_gamble_base_slots[64]    base BG CRAM slots 0-7 (CGB order, low first)

Sources (single sources of truth, never hand-copied):
  combat art cells  assets/battle_sprites.png via compose_battle_sprites
                    TILE_COORDS (frame0 of screens/combat_art/kobold.json,
                    geometry asserted 3x2 + oam:true here -- fail loudly
                    if the artist changes it instead of silently
                    mis-stamping)
  kobold ramp       assets/palette.txt via palette_parse (obj_palette of
                    screens/combat_art/kobold.json)
  base slots        generated/tiles/base.json (palette_compiler output)

Deterministic: rerunning reproduces the header byte-identically.
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "tools"))
sys.path.insert(0, str(REPO_ROOT / "tools" / "screen_compiler"))

from PIL import Image
from palette_parse import parse_palette
from compose_battle_sprites import TILE_COORDS
import json


def rgb555_lo_hi(rgb):
    v = ((rgb[0] >> 3) | ((rgb[1] >> 3) << 5) | ((rgb[2] >> 3) << 10)) & 0x7FFF
    return v & 0xFF, (v >> 8) & 0xFF


def main():
    art_path = REPO_ROOT / "screens" / "combat_art" / "kobold.json"
    art = json.loads(art_path.read_text())
    assert art.get("width") == 3 and art.get("height") == 2, \
        "gamble: kobold art must stay 3x2 (stamping + OAM stride assume it)"
    assert art.get("oam") is True, "gamble: kobold art must stay OAM (OBJ ramp path)"
    assert art.get("obj_palette") == "fightgoblin", \
        "gamble: kobold obj_palette must stay fightgoblin"

    cells = art["frame0"]
    assert len(cells) == 6, "gamble: kobold frame0 must hold 6 cells"
    sheet = Image.open(REPO_ROOT / "assets" / "battle_sprites.png").convert("RGB")

    _, ramps = parse_palette()
    obj_ramp = ramps[art["obj_palette"]]
    base = json.loads((REPO_ROOT / "generated" / "tiles" / "base.json").read_text())["slots"]

    out = []
    out.append("/**")
    out.append(" * Generated by tools/gamble_art_compile.py. DO NOT EDIT.")
    out.append(" * Kobold combat-art bytes + OBJ ramp + base BG CRAM slots for")
    out.append(" * the bank-8 gamble entry body (same bank, plain reads).")
    out.append(" */")
    out.append("")
    out.append("#ifndef GAMBLE_ART_H")
    out.append("#define GAMBLE_ART_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    # Tile bytes: nearest-shade encode like png2gb (ramps win, exact match
    # expected for artist pixels; nearest fallback mirrors the pipeline).
    out.append("/* Kobold frame0 (3x2, row-major), fightgoblin-encoded. */")
    out.append("static const uint8_t g_gamble_kobold_tiles[96] = {")
    blob = []
    for name in cells:
        assert name in TILE_COORDS, "gamble: unknown combat cell %r" % name
        cx, cy = TILE_COORDS[name]
        tile = sheet.crop((cx * 8, cy * 8, (cx + 1) * 8, (cy + 1) * 8))
        px = tile.load()
        for yy in range(8):
            byte0 = 0
            byte1 = 0
            for xx in range(8):
                r, g, b = px[xx, yy]
                best, best_d = 0, None
                for i, c in enumerate(obj_ramp):
                    d = (r - c[0]) ** 2 + (g - c[1]) ** 2 + (b - c[2]) ** 2
                    if best_d is None or d < best_d:
                        best, best_d = i, d
                # GB 2bpp: low bit plane first.
                if best & 1:
                    byte0 |= (1 << (7 - xx))
                if best & 2:
                    byte1 |= (1 << (7 - xx))
            blob.append("0x%02X, 0x%02X" % (byte0, byte1))
    for i in range(0, len(blob), 4):
        out.append("    " + ", ".join(blob[i:i + 4]) + ",")
    out.append("};")
    out.append("")
    out.append("/* fightgoblin OBJ ramp (CGB order, low first). */")
    pairs = ", ".join("0x%02X, 0x%02X" % rgb555_lo_hi(c) for c in obj_ramp)
    out.append("static const uint8_t g_gamble_kobold_ramp[8] = { %s };" % pairs)
    out.append("")
    out.append("/* Base BG CRAM slots 0-7 (CGB order, low first). */")
    out.append("static const uint8_t g_gamble_base_slots[64] = {")
    for slot in range(8):
        colors = base[str(slot)]["colors"]
        pairs = ", ".join(
            "0x%02X, 0x%02X" % rgb555_lo_hi(tuple(int(colors[k][i:i + 2], 16) for i in (1, 3, 5)))
            for k in range(4))
        out.append("    /* %d */ %s," % (slot, pairs))
    out.append("};")
    out.append("")
    out.append("#endif /* GAMBLE_ART_H */")
    out.append("")
    header = REPO_ROOT / "src" / "gfx" / "gamble_art.h"
    text = "\n".join(out)
    # Write only on change: the header is a build prerequisite, so
    # rewriting it unconditionally would retrigger the gamble objects on
    # every build.
    try:
        if header.read_text() == text:
            print("src/gfx/gamble_art.h unchanged")
            return
    except OSError:
        pass
    header.write_text(text)
    print("wrote src/gfx/gamble_art.h")


if __name__ == "__main__":
    main()
