#!/usr/bin/env python3
"""Compile bird-chirp PCM files to Game Boy wave-channel data.

Reads assets/music/bird1.pcm + bird2.pcm (8-bit unsigned PCM, silence at
0x80) and emits generated/birds/bird_data.c (#pragma bank 7): each chirp
as packed 4-bit wave frames (16 bytes = 32 samples, high nibble first to
match the wave-RAM layout the stepper writes), plus lengths.

Deterministic: rerunning reproduces the file byte-identically.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSETS = REPO / "assets" / "music"
OUT_DIR = REPO / "generated" / "birds"

BIRDS = [("bird1", "BIRD_1"), ("bird2", "BIRD_2")]


def convert(path):
    raw = open(path, "rb").read()
    nibbles = [(v >> 4) & 0x0F for v in raw]
    if len(nibbles) % 2:
        nibbles.append(8)
    packed = bytearray()
    for i in range(0, len(nibbles), 2):
        packed.append((nibbles[i] << 4) | nibbles[i + 1])
    # Pad to whole 16-byte wave frames with silence (0x88).
    while len(packed) % 16:
        packed.append(0x88)
    return packed


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = []
    out.append("/* Generated by tools/bird_compile.py -- DO NOT EDIT DIRECTLY */")
    out.append("#pragma bank 7")
    out.append("")
    out.append('#include <stdint.h>')
    out.append("")
    max_frames = 0
    for stem, const in BIRDS:
        packed = convert(ASSETS / (stem + ".pcm"))
        frames = len(packed) // 16
        if frames > max_frames:
            max_frames = frames
        out.append("/* %s.pcm: %d bytes -> %d wave frames (%d bytes). */"
                   % (stem, len(open(ASSETS / (stem + ".pcm"), "rb").read()),
                      frames, len(packed)))
        out.append("const uint8_t g_bird_%s[%d] = {" % (stem, len(packed)))
        for i in range(0, len(packed), 8):
            out.append("    %s," % ", ".join("0x%02X" % b for b in packed[i:i + 8]))
        out.append("};")
        out.append("const uint8_t g_bird_%s_frames = %d;" % (stem, frames))
        out.append("")
    (OUT_DIR / "bird_data.c").write_text("\n".join(out))
    (OUT_DIR / "bird_data.h").write_text(
        "/* Generated by tools/bird_compile.py -- DO NOT EDIT DIRECTLY */\n"
        "#ifndef BIRD_DATA_H\n"
        "#define BIRD_DATA_H\n"
        "#include <stdint.h>\n"
        "/* Longest chirp in wave frames: the overworld streamer sizes its\n"
        " * window from this (one wave frame per overworld frame, then one\n"
        " * cleanup frame), so new/longer chirps never overflow the window. */\n"
        "#define BIRD_MAX_FRAMES %d\n"
        "extern const uint8_t g_bird_bird1[];\n"
        "extern const uint8_t g_bird_bird1_frames;\n"
        "extern const uint8_t g_bird_bird2[];\n"
        "extern const uint8_t g_bird_bird2_frames;\n"
        "#endif\n" % max_frames)
    print("wrote generated/birds/bird_data.c")


if __name__ == "__main__":
    sys.exit(main())
