#!/usr/bin/env python3
"""Generate assets/travel-chrome-shades.json from assets/travel-tile.png.

Per-tile ordered light->dark ramps for png2gb --shade-map (opaque sheet,
no transparency). Tiles with >4 shades keep the 4 most frequent
(luminance extremes preserved); off-ramp pixels fall back to the
nearest ramp shade inside png2gb.

Regenerate when the artist updates assets/travel-tile.png:
  python3 tools/travel_chrome_shades.py
"""
import json
from pathlib import Path
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "assets" / "travel-tile.png"
OUT = REPO / "assets" / "travel-chrome-shades.json"


def lum(rgb):
    r, g, b = rgb
    return 0.299 * r + 0.587 * g + 0.114 * b


def main():
    im = Image.open(SRC).convert("RGB")
    w, h = im.size
    assert (w, h) == (160, 16), (w, h)
    tiles = {}
    for ty in range(h // 8):
        for tx in range(w // 8):
            cell = im.crop((tx * 8, ty * 8, tx * 8 + 8, ty * 8 + 8))
            counts = sorted(cell.getcolors(64), reverse=True)
            uniq = [c for _, c in counts]
            uniq.sort(key=lum, reverse=True)
            if len(uniq) > 4:
                # keep extremes + 2 most frequent middles (nearest fallback
                # covers the dropped shade inside png2gb)
                mid = sorted(counts[1:-1], reverse=True)[:2]
                keep = {uniq[0], uniq[-1]} | {c for _, c in mid}
                uniq = sorted(keep, key=lum, reverse=True)
                while len(uniq) < 4:
                    uniq.append(uniq[-1])
            while len(uniq) < 4:
                uniq.append(uniq[-1])
            tiles["%d,%d" % (tx, ty)] = ["#%02X%02X%02X" % c for c in uniq]
    doc = {
        "_note": ("Per-tile light->dark ramps for assets/travel-tile.png "
                  "(travel chrome: box, icons, labels, markers, floors). "
                  "Generated by tools/travel_chrome_shades.py -- do not hand-edit. "
                  "Ramp order is the 2bpp index order; a future CRAM pass can "
                  "reuse these ramps as palette slots."),
        "tiles": tiles,
    }
    OUT.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print("wrote %s (%d tiles)" % (OUT.relative_to(REPO), len(tiles)))


if __name__ == "__main__":
    main()
