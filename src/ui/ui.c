/* ASCII semantic char per TileType (0..3): '.', '#', '>', 'B'.  The
 * overworld renders these via the console font (ui_font_tile_base + (ch -
 * ' ')); this branch is ASCII-only -- real terrain tiles live on the gfx
 * branch. */
static const char g_sem_map[8] = { '.', '#', '>', 'B', '1', '2', '3', '4' };

void ui_init(void)
{
    uint8_t p;

    /* Turn the LCD off before loading the font so that display_off() inside
     * set_bkg_data() returns immediately (it waits for VBlank otherwise).
     * The CRT0 boot already leaves the LCD off; the harness (which skips
     * CRT0) needs this too, and mGBA's debugger does not advance VBlank
     * during single-stepping.  Clear bit 4 for signed 0x9000 tile addressing. */
    LCDC_REG &= ~0x90;

    oam_dma_init();

    /* Load font tiles from Bank 5 (96 tiles = 1536 bytes) using g_ui_screen_buf as temporary buffer */
    for (p = 0; p < 96; p += 8) {
        banked_copy(5, g_ui_screen_buf, g_intrepid_font_tiles + ((uint16_t)p << 4), 128);
        set_bkg_data(p, 8, (const uint8_t *)g_ui_screen_buf);
        /* The overworld renders actors as OAM sprites that reference the
         * font glyph tiles, but sprites always read from the 0x8000 VRAM
         * block while the LCDC bit-4 = 0 signed map puts the font in 0x9000.
         * Duplicate each font tile into the sprite block so actor sprites
         * (glyph index = visual - ' ') have real glyph data (AGENTS.md). */
        set_sprite_data(p, 8, (const uint8_t *)g_ui_screen_buf);
    }
    ui_font_tile_base = 0;

    /* Battle UI tiles (card frames, timer-bar segments, HUD hp/ap/deck
     * icons, light/dark select arrows, weapon icons, gold-coin tile) stream
     * from Bank 3
     * (generated card_frame_tiles.h + bank-local coin tile, make gfx) through
     * the banked loader
     * -- the fixed bank stays lean (AGENTS.md 52.18).  VRAM (signed BG
     * block, 0x9000-based: AGENTS.md 52.22): frames 118-126, bar 117/127,
     * HUD icons at 113/114/116 (sheet tiles
     * 11-13), light arrow at 96 (sheet tile 14), dark arrow at 110
     * (sheet tile 15), weapons overwrite the atlas data at 104-108
     * (sheet tiles 16-20), spare blank at 97.  Runs with
     * the LCD still off. */
    g_bk_call_bank = 3;
    g_bk_call_target = (uint16_t)&ui_card_tiles_load_banked;
    banked_call_run();

    /* Reset tileset cache; active scene will load its tileset dynamically */
    s_loaded_tileset = -1;

    /* Disable GBDK console auto-scroll.  When putchar() advances the cursor
     * past the bottom-right tile, the console normally scrolls the whole
     * screen up one line.  M_NO_SCROLL (bit 2 of the console .mode byte,
     * exposed as console_mode by crt0.s) makes it reset the cursor instead. */
    console_mode |= M_NO_SCROLL;

    /* Set DMG palettes: 0xE4 = 11 10 01 00 (Lightest to Darkest) */
    BGP_REG = 0xE4;
    OBP0_REG = 0xE4;
    OBP1_REG = 0xE4;

    /* CGB detection (see g_is_cgb): on CGB VBK unused bits 1-7 read as 1,
     * so writing 0 reads back as 0xFE and writing 1 reads as 0xFF.  On DMG
     * (open bus or unmapped) VBK is constant 0xFF (real HW) or 0 (simple emus). */
    VBK_REG = 0;
    p = VBK_REG;
    VBK_REG = 1;
    g_is_cgb = (p == 0xFE && VBK_REG == 0xFF);
    VBK_REG = 0;

    /* Program all 8 BG palettes via banked loader in Bank 5. */
    ui_set_cram_palette(0);
    /* OBJ slots 0-7: generated (artist ramps 0-4, grey 5-7). */
    OCPS_REG = 0x80;
    for (p = 0; p < 64; p++) {
        OCPD_REG = ((const uint8_t *)cgb_obj_palettes)[p];
    }

    SHOW_BKG;

    ui_sprite_init();
    DISPLAY_ON;
}

/* Load the player sprite tile and enable the OAM sprite.  Called from
 * ui_init() while the LCD is still off: set_sprite_data() writes VRAM
 * through the same path as set_bkg_data() (both live in set_data.o) and
 * returns immediately while the LCD is off, so this stays harness-safe
 * (AGENTS.md 52.6).  The sprite starts hidden (OAM Y = 0); the overworld
 * render positions it via ui_sprite_move(). */
void ui_sprite_init(void)
{
    extern const uint8_t enemy_ow_tiles[];
    extern const uint8_t g_enemy_ow_tile_count;
    uint8_t ow_n, t, c;

    /* Hero overworld art: exactly 2 tiles = frames 1 & 2 (assets/
     * hero_sprites.png).  The old idle tile was loaded then overwritten
     * here; the player OAM slot now only ever shows frames 1 & 2 (see
     * ui_draw_actors_sprites). */
    set_sprite_data(HERO_DESOLATE_SPRITE_TILE_ID, 2, hero_desolate_sprite_tile);
    /* Shared per-enemy overworld sprites (bank-8 blob, see
     * src/game/enemy_ow_content.c, with its size in bank-8
     * src/game/enemy_ow_count.c): stream into OAM at ENEMY_OW_BASE in
     * screen-buf chunks (g_ui_screen_buf holds 128 bytes safely; no
     * multiply anywhere). */
    banked_copy(8, &ow_n, &g_enemy_ow_tile_count, 1);
    for (t = 0; t < ow_n; t = (uint8_t)(t + 8)) {
        c = (uint8_t)(ow_n - t);
        if (c > 8) c = 8;
        banked_copy(8, (void *)g_ui_screen_buf,
                    (const void *)&enemy_ow_tiles[(uint16_t)t << 4],
                    (uint16_t)c << 4);
        set_sprite_data((uint8_t)(ENEMY_OW_BASE + t), c,
                        (const uint8_t *)g_ui_screen_buf);
    }
    /* Chest OAM (SPRITE_KIND_CHEST statics): the shared-blob closed/open
     * frames stream with the enemy blob above; the banked sprite body
     * picks the frame from loot state. */
    shadow_OAM[PLAYER_SPRITE_NUM].tile = PLAYER_SPRITE_TILE_ID;
    shadow_OAM[PLAYER_SPRITE_NUM].y = 0;
    SPRITES_8x8;
    SHOW_SPRITES;
}

void ui_sprite_move(uint8_t px, uint8_t py)
{
    shadow_OAM[PLAYER_SPRITE_NUM].y = (uint8_t)(py + 16);
    shadow_OAM[PLAYER_SPRITE_NUM].x = (uint8_t)(px + 8);
}

/* Hide the player sprite (OAM Y = 0).  Called on transitions away from the
 * overworld so the blob does not float over battle/menu screens.  The sprite
 * is also hidden in real OAM immediately (see ui_sprite_begin_transition)
 * so it is gone before the new screen's full redraw starts wiping the
 * display. */
void ui_sprite_hide(void)
{
    ui_sprite_begin_transition();
}

