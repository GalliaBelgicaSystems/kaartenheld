void ui_set_cram_palette(uint8_t overworld)
{
    if (!g_is_cgb) return;
    g_bk_call_bank = 5;
    g_bk_call_target = (uint16_t)&ui_load_cram_banked;
    g_bk_byte_a = overworld;
    banked_call_run();
}

